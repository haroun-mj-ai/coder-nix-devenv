#!/usr/bin/env python3
"""Render docs/TOOL-SOURCES.md from bootstrap/manifest.tsv.

    ./scripts/render-tool-sources.py           # rewrite docs/TOOL-SOURCES.md
    ./scripts/render-tool-sources.py --check   # exit 1 if the doc is stale

The manifest is the source of truth; never hand-edit the generated doc.
Standard library only, so it runs on a bare Ubuntu python3.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "bootstrap" / "manifest.tsv"
OUT = ROOT / "docs" / "TOOL-SOURCES.md"

LAYERS = [
    ("base", "Base toolchain (this repo's `flake.nix`)"),
    ("extras", "Extras (the `coder-packages` layer)"),
    ("runtime", "Runtime binaries this box executes from `/nix/store` today"),
]


def cell(s: str) -> str:
    return s.replace("|", "\\|")


def source(r: dict) -> str:
    kind = f"`{r['source_kind']}`"
    if r["source_kind"] == "apt":
        return f"{kind} `{r['bins']}` (Ubuntu 26.04)"
    if r["source_kind"] == "none":
        return kind
    ux, ua = r["url_x86_64"], r["url_arm64"]
    if ux == ua:
        return f"{kind} <{ux}> (any arch)"
    return f"{kind} x86_64: <{ux}><br>arm64: <{ua}>"


def has_delta(r: dict) -> bool:
    """A real version gap. 'Exact match' rows differ only in how the version is spelled."""
    nv = r["nix_version"]
    return nv not in ("-", "") and nv != r["upstream_version"] and not r["notes"].startswith("Exact match")


def notes(r: dict) -> str:
    n = r["notes"]
    nv, uv = r["nix_version"], r["upstream_version"]
    if has_delta(r):
        n = f"**Δ nix {nv} → upstream {uv}.** {n}"
    return cell(n)


def render(rows: list) -> str:
    out = [
        "# Tool sources (nix-free)",
        "",
        "<!-- Generated by scripts/render-tool-sources.py from bootstrap/manifest.tsv."
        " Do not hand-edit. -->",
        "",
        "Where every tool comes from once Nix is gone. The machine-readable version,",
        "with the sha256 of every artifact, is [`bootstrap/manifest.tsv`](../bootstrap/manifest.tsv);",
        "[`bootstrap/install.sh`](../bootstrap/install.sh) installs from it.",
        "",
        "- **Source kinds.** `github-release`: a GitHub release asset. `tarball` / `zip`:",
        "  a vendor-hosted versioned download (ngrok's is a bare binary despite the kind).",
        "  `pip`: a PyPI wheel installed into its own venv. `apt`: Ubuntu 26.04 archive.",
        "- **Hashes.** Every non-apt sha256 was computed from the downloaded bytes by",
        "  `bootstrap/update-hashes.sh`, then cross-checked against an independent source",
        "  (upstream checksum file, GitHub asset digest, or nix's own fixed-output hash).",
        "  See [DEAD-URLS.md](DEAD-URLS.md) for the URL audit.",
        "- **Versions.** Upstream versions for pinned artifacts are what the downloaded",
        "  binary itself printed (`bootstrap/verify.sh`). apt versions are the Ubuntu 26.04",
        "  candidate on 2026-11-25 and drift with Ubuntu updates.",
        "- **Δ** marks a tool whose nix version has no exact non-nix equivalent; the nearest",
        "  real upstream release is used and the delta is spelled out.",
        "",
    ]
    for layer, title in LAYERS:
        sel = [r for r in rows if r["layer"] == layer]
        if not sel:
            continue
        out += [
            f"## {title}",
            "",
            "| Tool | Nix version | Upstream version | Source | License | Notes |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for r in sel:
            out.append(
                f"| `{r['tool']}` | {cell(r['nix_version'])} | {cell(r['upstream_version'])}"
                f" | {source(r)} | {cell(r['license'])} | {notes(r)} |"
            )
        out.append("")
    kinds = {}
    for r in rows:
        kinds[r["source_kind"]] = kinds.get(r["source_kind"], 0) + 1
    deltas = sum(1 for r in rows if has_delta(r))
    out += [
        "## Totals",
        "",
        f"- {len(rows)} tools: "
        + ", ".join(f"{sum(1 for r in rows if r['layer'] == l)} {l}" for l, _ in LAYERS),
        "- by source: " + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())),
        f"- {deltas} with a nix → upstream version delta",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    with MANIFEST.open(newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))
    text = render(rows)
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/render-tool-sources.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
